"""
Deterministic extractive question answering (revised Phases 10/11).

Pipeline: tokenize -> drop stopwords -> light stemming -> synonym expansion
into "concepts" -> BM25 ranking over content chunks -> coverage check ->
extract the best sentences verbatim -> cite the source -> refuse when the
evidence is too thin. No embedding model, no vector DB, no LLM, and
therefore no possibility of a fabricated health answer: every word of an
answer is copied from approved training content.

THIS FILE IS MIRRORED LINE-FOR-LINE by mobile/lib/qa/qa_engine.dart so the
phone answers identically with or without a connection. Parity is enforced
by tests/qa_vectors.json (generated by scripts/generate_qa_vectors.py and
copied to mobile/test/): the Python tests and the Dart tests both replay
the same vectors. Keep both implementations in lockstep — any change here
must be made there too and the vectors regenerated.

Float-sensitive steps deliberately use integer arithmetic (percentages,
scaled scores) so Python and Dart cannot disagree on rounding.
"""
import math
import re

K1 = 1.5
B = 0.75
DEFAULT_MIN_COVERAGE_PCT = 50

FALLBACK_MESSAGE = "I couldn't find a reliable answer to this question in your downloaded training materials."

SUGGESTIONS = [
    "Who is eligible for AZM?",
    "How much AZM should a child receive?",
    "When should a child be referred to a health facility?",
    "What should I do if a child vomits after the medicine?",
]

STOPWORDS = frozenset(
    "a about above after again all also am an and any are as at be because been before being below between "
    "both but by can could did do does doing down during each few for from further had has have having he her "
    "here hers him his how i if in into is it its just me more most my no nor not of off on once only or other "
    "our out over own same she should so some such than that the their them then there these they this those "
    "through to too under until up very was we were what when where which while who whom why will with would "
    "you your".split()
)

# Single-word synonym groups. A query term expands to every group containing
# its stem; a term in several groups gets the union. All words are stemmed
# with the same stem() as everything else.
SYNONYM_GROUPS = [
    ["vomit", "vomiting", "vomited", "retch", "puke", "regurgitate", "threw", "throw", "thrown", "spit", "spat"],
    ["medicine", "drug", "medication", "tablet", "suspension", "antibiotic", "dose", "dosage", "dosing"],
    ["azm", "azithromycin", "medicine", "drug", "medication"],
    ["much", "amount", "quantity", "volume", "ml", "dose", "dosage", "dosing"],
    ["prepare", "mix", "reconstitute", "dissolve", "shake", "dilute"],
    ["child", "children", "infant", "baby", "toddler", "kid", "kids"],
    ["age", "aged", "old", "older", "year", "years", "month", "months", "young", "younger", "newborn", "neonate"],
    ["eligible", "eligibility", "qualify", "allowed", "receive"],
    ["sick", "ill", "unwell", "illness"],
    ["fever", "temperature", "hot"],
    ["refer", "referral", "referred", "facility", "clinic", "hospital"],
    ["report", "contact", "email", "concern", "complaint", "escalate"],
    ["malnutrition", "malnourished", "muac", "wasting", "sam", "thin", "skinny", "underweight", "emaciated", "armband"],
    ["allergy", "allergic", "allergies", "reaction", "rash", "swelling"],
    ["photo", "photograph", "picture", "camera"],
    ["house", "home", "household", "compound", "chalk", "mark", "marking", "marked"],
    ["record", "recording", "card", "register"],
    ["caregiver", "parent", "mother", "guardian", "mum"],
    ["safeguard", "safeguarding", "abuse", "abused", "protection", "protect", "harm", "exploitation", "misconduct"],
    ["pregnant", "pregnancy", "anc", "antenatal"],
]


def _is_number(token):
    for c in token:
        if c not in "0123456789":
            return False
    return len(token) > 0


def tokenize(text):
    """Lowercase, split on any non-alphanumeric character (Unicode-aware, so
    Hausa/Fulfulde/Kanuri letters survive), keep numbers and tokens of 2+
    characters."""
    tokens = []
    current = []
    for ch in text.lower():
        if ch.isalnum():
            current.append(ch)
        else:
            if current:
                tokens.append("".join(current))
                current = []
    if current:
        tokens.append("".join(current))
    return [t for t in tokens if _is_number(t) or len(t) >= 2]


def stem(token):
    t = token
    if _is_number(t):
        return t
    if len(t) > 5 and t.endswith("ing"):
        t = t[:-3]
    elif len(t) > 4 and t.endswith("ed"):
        t = t[:-2]
    elif len(t) > 4 and t.endswith("es"):
        t = t[:-2]
    elif len(t) > 3 and t.endswith("s") and not t.endswith("ss"):
        t = t[:-1]
    if len(t) > 3 and t.endswith("e"):
        t = t[:-1]
    return t


def content_terms(text):
    """Stemmed, de-duplicated, stopword-free terms of a question, in order."""
    seen = set()
    out = []
    for tok in tokenize(text):
        if tok in STOPWORDS:
            continue
        s = stem(tok)
        if s not in seen:
            seen.add(s)
            out.append(s)
    return out


def _build_synonym_index():
    index = {}
    for group in SYNONYM_GROUPS:
        stems = set(stem(w) for w in group)
        for s in stems:
            if s not in index:
                index[s] = set()
            index[s].update(stems)
    return index


_SYNONYM_INDEX = _build_synonym_index()


def expand(term_stem):
    out = set([term_stem])
    if term_stem in _SYNONYM_INDEX:
        out.update(_SYNONYM_INDEX[term_stem])
    return out


_YEARS_RE = re.compile(r"\b(\d{1,2})\s*(?:-|\s)?\s*(?:years?|yrs?)\b", re.IGNORECASE)


def normalize_ages(question):
    """The training tables are written in months, so '2 year old' must be
    read as '24 month old'. Without this a 2-year-old matched the '1-2
    months: 2 ml' dose row, which is a dosing error."""
    return _YEARS_RE.sub(lambda m: f"{int(m.group(1)) * 12} months", question)


def build_concepts(question):
    question = normalize_ages(question)
    """One concept per distinct (synonym-expanded) question term."""
    concepts = []
    seen = set()
    for term in content_terms(question):
        c = expand(term)
        key = "|".join(sorted(c))
        if key in seen:
            continue
        seen.add(key)
        concepts.append(c)
    return concepts


def _doc_terms(text):
    return [stem(t) for t in tokenize(text) if t not in STOPWORDS]


def build_index(chunks):
    docs = []
    total_len = 0
    for ch in chunks:
        title = ch.get("section_title") or ""
        terms = _doc_terms(title + " . " + ch["chunk_text"])
        tf = {}
        for t in terms:
            tf[t] = tf.get(t, 0) + 1
        docs.append({"chunk": ch, "tf": tf, "len": len(terms)})
        total_len += len(terms)
    avgdl = (total_len / len(docs)) if docs else 0.0
    return {"docs": docs, "avgdl": avgdl}


def rank(concepts, index):
    docs = index["docs"]
    avgdl = index["avgdl"]
    if not concepts or not docs or avgdl == 0:
        return []
    n = len(docs)
    idfs = []
    for c in concepts:
        df = 0
        for d in docs:
            for s in c:
                if s in d["tf"]:
                    df += 1
                    break
        idfs.append(math.log(1 + (n - df + 0.5) / (df + 0.5)))
    results = []
    for d in docs:
        score = 0.0
        matched = 0
        for i, c in enumerate(concepts):
            tf = 0
            for s in c:
                tf += d["tf"].get(s, 0)
            if tf > 0:
                matched += 1
                denom = tf + K1 * (1 - B + B * d["len"] / avgdl)
                score += idfs[i] * (tf * (K1 + 1)) / denom
        results.append({"doc": d, "score": score, "score_i": int(score * 1000000 + 0.5), "matched": matched})
    results.sort(key=lambda r: (-r["score_i"], r["doc"]["chunk"]["id"]))
    return results


def split_sentences(text):
    t = text
    for mark in (".", "!", "?"):
        t = t.replace(mark + " ", mark + "\n")
    t = t.replace(" \u00b7 ", "\n")
    return [s.strip() for s in t.split("\n") if s.strip()]


_DECIMAL = re.compile(r"[0-9]+\.[0-9]+")
_PARENS = re.compile(r"\([^)]*\)")
_RANGE = re.compile(r"([0-9]{1,9})\s*[\u2013\u2014-]\s*([0-9]{1,9})")


def _ranges(sentence):
    """Numeric ranges like '3-4 months' or '12-59 months' in a sentence.
    Parenthesised text (e.g. a table header '(1-11 months)') and decimals
    (e.g. '11.5 - 12.4 cm') are ignored so they can't create bogus ranges."""
    t = _PARENS.sub(" ", sentence)
    t = _DECIMAL.sub(" ", t)
    out = []
    for m in _RANGE.finditer(t):
        lo = int(m.group(1))
        hi = int(m.group(2))
        if lo <= hi:
            out.append((lo, hi))
    return out


def _concept_hit(stems, ranges, concept):
    """A concept is hit if any of its stems appears in the sentence. Numbers
    are range-aware: in a sentence that contains ranges, a number only
    matches if it falls INSIDE one of them (so '4' matches '3-4 months' but
    not the dose value in '5-11 months; Dose: 4 ml') — this is what stops a
    dosing question from picking up the wrong age row."""
    for s in concept:
        if _is_number(s):
            if ranges:
                if len(s) <= 9:
                    n = int(s)
                    for lo, hi in ranges:
                        if lo <= n <= hi:
                            return True
            elif s in stems:
                return True
        elif s in stems:
            return True
    return False


def _sentence_coverage(sentence, concepts):
    stems = set(_doc_terms(sentence))
    ranges = _ranges(sentence)
    covered = 0
    for c in concepts:
        if _concept_hit(stems, ranges, c):
            covered += 1
    return covered


def _best_sentence_cov(chunk_text, concepts):
    best = 0
    for sentence in split_sentences(chunk_text):
        c = _sentence_coverage(sentence, concepts)
        if c > best:
            best = c
    return best


def best_sentences(chunk_text, concepts, limit=2):
    """The most relevant sentence(s), verbatim. A second sentence is added
    only when it is AS relevant as the first (covers the same number of
    question concepts) — so a 'severe malnutrition' question returns the
    severe row, not the moderate one too. [] if no sentence matches."""
    sentences = split_sentences(chunk_text)
    scored = []
    for i, sent in enumerate(sentences):
        cov = _sentence_coverage(sent, concepts)
        if cov > 0:
            scored.append((i, cov, sent))
    if not scored:
        return []
    scored.sort(key=lambda x: (-x[1], x[0]))
    chosen = [scored[0]]
    if limit > 1 and len(scored) > 1 and scored[1][1] == scored[0][1]:
        chosen.append(scored[1])
    chosen.sort(key=lambda x: x[0])
    return [c[2] for c in chosen]


def _pct(matched, total):
    return (100 * matched + total // 2) // total


def _source(chunk, snippet):
    return {
        "chunk_id": chunk["id"],
        "module_id": chunk.get("module_id"),
        "section_id": chunk.get("section_id"),
        "module_code": chunk["module_code"],
        "module_title": chunk["source_title"],
        "section_title": chunk.get("section_title"),
        "snippet": snippet,
    }


def _fallback(confidence_pct=0):
    return {
        "answer": FALLBACK_MESSAGE,
        "matched": False,
        "confidence": confidence_pct / 100,
        "offline": False,
        "sources": [],
        "suggestions": list(SUGGESTIONS),
    }


def answer_question(question, chunks_or_index, min_coverage_pct=DEFAULT_MIN_COVERAGE_PCT):
    index = chunks_or_index if isinstance(chunks_or_index, dict) else build_index(chunks_or_index)
    concepts = build_concepts(question)
    ranked = rank(concepts, index)
    candidates = [r for r in ranked if r["matched"] > 0 and r["score_i"] > 0]
    if not candidates:
        return _fallback()

    # Re-rank: the chunk holding the single sentence that covers the most
    # question concepts wins; chunk-level concept coverage, then BM25, break
    # ties. (Pure BM25 favoured short chunks that merely repeat common words.)
    for r in candidates:
        r["sent_cov"] = _best_sentence_cov(r["doc"]["chunk"]["chunk_text"], concepts)
    candidates.sort(key=lambda r: (-r["sent_cov"], -r["matched"], -r["score_i"], r["doc"]["chunk"]["id"]))

    best = candidates[0]
    coverage_pct = _pct(best["matched"], len(concepts))
    if best["sent_cov"] == 0 or coverage_pct < min_coverage_pct:
        return _fallback(coverage_pct)

    best_chunk = best["doc"]["chunk"]
    sentences = best_sentences(best_chunk["chunk_text"], concepts, limit=2)
    sources = [_source(best_chunk, sentences[0])]

    for r in candidates[1:]:
        if len(sources) >= 3:
            break
        if r["sent_cov"] < min(2, best["sent_cov"]) or _pct(r["matched"], len(concepts)) < min_coverage_pct:
            continue
        if r["score_i"] * 2 < best["score_i"]:
            continue
        sn = best_sentences(r["doc"]["chunk"]["chunk_text"], concepts, limit=1)
        if sn:
            sources.append(_source(r["doc"]["chunk"], sn[0]))

    return {
        "answer": " ".join(sentences),
        "matched": True,
        "confidence": coverage_pct / 100,
        "offline": False,
        "sources": sources,
        "suggestions": [],
    }
