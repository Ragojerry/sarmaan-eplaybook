"""Copies the English consent text (with the privacy notice) into the app, as the
copy shown on a phone that has never been online.

    python scripts/consent_sync.py           write mobile/lib/models/consent_body_en.g.dart
    python scripts/consent_sync.py --check   fail if the Dart copy is stale

Source: content/privacy_notice/consent_body_en.txt. The live text is edited in the
admin portal (Consent text); paste this file there when the notice changes.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "content" / "privacy_notice" / "consent_body_en.txt"
OUT = ROOT / "mobile" / "lib" / "models" / "consent_body_en.g.dart"


def render() -> str:
    body = SRC.read_text(encoding="utf-8").strip()
    literal = json.dumps(body, ensure_ascii=False).replace("$", "\\$")  # a JSON string is a valid Dart string
    return (
        "// GENERATED by scripts/consent_sync.py from content/privacy_notice/consent_body_en.txt. Do not edit.\n\n"
        "/// The English consent text with the full privacy notice, built into the app.\n"
        f"const kBundledConsentBody =\n    {literal};\n"
    )


def main(check: bool) -> int:
    text = render()
    if check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python scripts/consent_sync.py")
            return 1
        print("consent copy up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
