"""
The mobile app's interface text: one English catalogue, spread to where it is used.

    python scripts/l10n_sync.py           # regenerate the copies
    python scripts/l10n_sync.py --check   # exit 1 if a copy is stale or the code uses an unknown key

Source: mobile/l10n/app_strings.json
    {"strings": {"home.title": {"en": "...", "note": "Where it appears"},
                 "home.sectionCount": {"en": "{count} sections", "en_one": "{count} section", "note": "..."}}}
`en_one` makes a string plural (the phone picks the form per language). Placeholders
are written {name}.

Writes:
    mobile/lib/l10n/app_strings_en.g.dart   English compiled into the app (offline default)
    backend/app/l10n/app_strings.json       what the backend seeds the registry from
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "mobile/l10n/app_strings.json"
DART_OUT = ROOT / "mobile/lib/l10n/app_strings_en.g.dart"
BACKEND_OUT = ROOT / "backend/app/l10n/app_strings.json"
DART_SRC = ROOT / "mobile/lib"

KEY = re.compile(r"^[a-z][a-zA-Z0-9]*(\.[a-z0-9][a-zA-Z0-9]*)+$")
PLACEHOLDER = re.compile(r"\{(\w+)\}")
# context.t('a.b'), context.tn('a.b', n), L10n.t('a.b'), L10n.n('a.b', n)
USAGE = re.compile(r"(?:\bcontext|\bctx|\bc|\bL10n)\.(t|tn|n)\(\s*'([^']+)'")


def load() -> dict:
    return json.loads(SOURCE.read_text(encoding="utf-8"))


def validate(catalog: dict) -> list[str]:
    problems = []
    for key, entry in catalog["strings"].items():
        if not KEY.match(key):
            problems.append(f"{key}: keys are dotted lowerCamel words, e.g. home.title")
        if not isinstance(entry.get("en"), str) or not entry["en"].strip():
            problems.append(f"{key}: English text is empty")
        if not (entry.get("note") or "").strip():
            problems.append(f"{key}: add a note for translators (where it appears)")
        if "en_one" in entry and PLACEHOLDER.findall(entry["en_one"]) and \
                set(PLACEHOLDER.findall(entry["en_one"])) - set(PLACEHOLDER.findall(entry["en"])):
            problems.append(f"{key}: the singular form uses a placeholder the plural form lacks")
    return problems


def _dart(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n") + "'"


def render_dart(catalog: dict) -> str:
    lines = [
        "// GENERATED by scripts/l10n_sync.py from mobile/l10n/app_strings.json. Do not edit.",
        "// English interface text, compiled in so the app works offline before any download.",
        "// Plural strings: `key` is the \"other\" form and `key#one` the singular.",
        "",
        "const Map<String, String> kEnglishStrings = {",
    ]
    for key in sorted(catalog["strings"]):
        entry = catalog["strings"][key]
        lines.append(f"  {_dart(key)}: {_dart(entry['en'])},")
        if "en_one" in entry:
            lines.append(f"  {_dart(key + '#one')}: {_dart(entry['en_one'])},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def render_backend(catalog: dict) -> str:
    return json.dumps(catalog, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def used_keys() -> dict[str, list[tuple[str, str]]]:
    """key -> [(file, call)] for every literal key the Dart code reads."""
    found: dict[str, list[tuple[str, str]]] = {}
    for path in DART_SRC.rglob("*.dart"):
        if path.name.endswith(".g.dart"):
            continue
        for m in USAGE.finditer(path.read_text(encoding="utf-8")):
            found.setdefault(m.group(2), []).append((str(path.relative_to(ROOT)), m.group(1)))
    return found


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")

    catalog = load()
    problems = validate(catalog)
    strings = catalog["strings"]

    used = used_keys()
    for key, where in sorted(used.items()):
        if key not in strings:
            problems.append(f"{key}: used in {where[0][0]} but missing from app_strings.json")
            continue
        plural = "en_one" in strings[key]
        for file, call in where:
            if plural and call == "t":
                problems.append(f"{key}: plural string read with t() in {file}; use tn()/L10n.n()")
            if not plural and call in ("tn", "n"):
                problems.append(f"{key}: read as plural in {file} but has no en_one form")
    unused = sorted(set(strings) - set(used))
    if unused:
        problems.append(f"{len(unused)} catalogue key(s) not used in the code (first: {unused[0]})")

    outputs = {DART_OUT: render_dart(catalog), BACKEND_OUT: render_backend(catalog)}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]

    if a.check:
        problems += [f"{p.relative_to(ROOT)} is out of date (run scripts/l10n_sync.py)" for p in stale]
        for p in problems:
            print("FAIL", p)
        plural_count = sum(1 for e in strings.values() if "en_one" in e)
        print(f"{len(strings)} strings ({plural_count} plural), {len(used)} keys used in code")
        return 1 if problems else 0

    if problems:
        for p in problems:
            print("FAIL", p)
        return 1
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p], encoding="utf-8")
        print("wrote", p.relative_to(ROOT))
    print(f"{len(strings)} strings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
