"""
Spreads brand/ (the one token file, the logo config and the logo files) to the
app and the admin portal:

  brand/tokens.json  -> mobile/lib/theme/brand_tokens.g.dart   (generated Dart)
                        mobile/android/.../values/brand_colors.xml (launch screen)
                        admin/src/brand/tokens.json (read by tailwind.config.js and src/brand/tokens.ts)
  brand/logos.json   -> mobile/assets/brand/logos.json, admin/src/brand/logos.json
  brand/brand.json   -> mobile/lib/theme/brand_identity.g.dart (title, logo asset and size),
                        mobile/android/.../values/brand_strings.xml (launcher label = short title),
                        admin/src/brand/brand.json (title, logo; also the browser tab title)
  brand/logos/*      -> mobile/assets/brand/, admin/public/brand/  (byte-for-byte copies)

Usage (from the repository root):
    python scripts/brand_sync.py          # write
    python scripts/brand_sync.py --check  # exit 1 if anything is out of date (CI / tests)
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "brand"


def tint(hex_colour: str, percent: float) -> str:
    """The colour at `percent` strength on white, the way the guide's tints are made."""
    h = hex_colour.lstrip("#")
    rgb = [int(h[i:i + 2], 16) for i in (0, 2, 4)]
    return "#" + "".join(f"{round(c * percent / 100 + 255 * (1 - percent / 100)):02X}" for c in rgb)


def resolved_colours(tokens: dict) -> dict[str, str]:
    colours = {k: v.upper() for k, v in tokens["palette"].items()}
    for name, (base, percent) in tokens["tints"].items():
        colours[name] = tint(colours[base], percent)
    for name, blend in tokens.get("blends", {}).items():
        if not name.startswith("_"):
            colours[name] = blend["hex"].upper()
    return colours


def _argb(hex_colour: str) -> str:
    return "0xFF" + hex_colour.lstrip("#").upper()


def dart_source(tokens: dict) -> str:
    colours = resolved_colours(tokens)
    out = [
        "// GENERATED by scripts/brand_sync.py from brand/tokens.json. Do not edit by hand.",
        "// ignore_for_file: constant_identifier_names",
        "import 'package:flutter/painting.dart';",
        "",
        "/// Brand palette and tints (brand/tokens.json).",
        "class BrandPalette {",
        "  BrandPalette._();",
    ]
    out += [f"  static const {k} = Color({_argb(v)}); // {v}" for k, v in colours.items()]
    out += ["}", "", "/// What each colour is for. Use these in widgets, never the palette directly.", "class BrandColors {",
            "  BrandColors._();"]
    out += [f"  static const {k} = BrandPalette.{v};" for k, v in tokens["semantic"].items()]
    font = tokens["font"]
    out += ["}", "", "class BrandFont {", "  BrandFont._();",
            f"  static const body = '{font['body']}';",
            f"  static const heading = '{font['heading']}';",
            f"  static const mono = '{font['mono']}';",
            "  static const fallback = <String>[" + ", ".join(f"'{f}'" for f in font["fallback"] if f != "sans-serif") + "];",
            "}", "", "class BrandTypeScale {", "  BrandTypeScale._();"]
    for name, t in tokens["typeScale"].items():
        out.append(f"  static const {name} = TextStyle(fontFamily: BrandFont.{t.get('family', 'body')}, fontFamilyFallback: BrandFont.fallback, "
                   f"fontSize: {t['size']}, fontWeight: FontWeight.w{t['weight']}, height: {t['lineHeight']}"
                   + (f", letterSpacing: {t['letterSpacing']}" if "letterSpacing" in t else "") + ");")
    out += ["}", "", "class BrandSpacing {", "  BrandSpacing._();"]
    out += [f"  static const double {k} = {v};" for k, v in tokens["spacing"].items()]
    out += ["}", "", "class BrandRadius {", "  BrandRadius._();"]
    out += [f"  static const double {k} = {v};" for k, v in tokens["radius"].items()]
    out += ["}", ""]
    return "\n".join(out)


def android_colours(tokens: dict) -> str:
    """The colours the native Android launch screen needs (resources cannot read JSON)."""
    colours = resolved_colours(tokens)
    return "\n".join([
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- GENERATED by scripts/brand_sync.py from brand/tokens.json. Do not edit by hand. -->",
        "<resources>",
        f'    <color name="brand_forest_green">{colours["forestGreen"]}</color>',
        f'    <color name="brand_primary">{colours[tokens["semantic"]["primary"]]}</color>',
        f'    <color name="brand_deep_forest">{colours["deepForest"]}</color>',
        f'    <color name="brand_white">{colours["white"]}</color>',
        "</resources>",
        "",
    ])


def _dart_string(s: str) -> str:
    """A single-quoted Dart string literal (backslash, quote and $ escaped)."""
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def identity_dart(brand: dict, logos: dict) -> str:
    logo = logos["logos"][brand["logo"]]
    return f"""// GENERATED by scripts/brand_sync.py from brand/brand.json and brand/logos.json. Do not edit.
// Change the title or the app logo there, then run: python scripts/brand_sync.py

/// The app's title and logo: read only through widgets/brand_mark.dart.
class BrandIdentity {{
  BrandIdentity._();

  static const title = {_dart_string(brand["title"])};

  /// Short form for narrow headers and the launcher label (approved 2026-11-13).
  static const shortTitle = {_dart_string(brand["shortTitle"])};

  static const logoAsset = {_dart_string("assets/brand/" + logo["file"])};
  static const logoLabel = {_dart_string(logo["label"])};
  static const logoWidthPx = {logo["widthPx"]};
  static const logoHeightPx = {logo["heightPx"]};
}}
"""


def android_strings(brand: dict) -> str:
    label = (brand["shortTitle"].replace("&", "&amp;").replace("<", "&lt;").replace("'", "\\'").replace('"', '\\"'))
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/brand_sync.py from brand/brand.json (shortTitle). Do not edit. -->
<resources>
    <!-- The name under the app icon (AndroidManifest android:label). -->
    <string name="app_label">{label}</string>
</resources>
"""


def targets() -> dict[Path, bytes]:
    tokens = json.loads((BRAND / "tokens.json").read_text(encoding="utf-8"))
    files = {ROOT / "mobile/lib/theme/brand_tokens.g.dart": dart_source(tokens).encode("utf-8"),
             ROOT / "mobile/android/app/src/main/res/values/brand_colors.xml": android_colours(tokens).encode("utf-8")}
    files[ROOT / "admin/src/brand/tokens.json"] = (BRAND / "tokens.json").read_bytes()
    logos_json = (BRAND / "logos.json").read_bytes()
    brand = json.loads((BRAND / "brand.json").read_text(encoding="utf-8"))
    files[ROOT / "mobile/lib/theme/brand_identity.g.dart"] = identity_dart(brand, json.loads(logos_json)).encode("utf-8")
    files[ROOT / "admin/src/brand/brand.json"] = (BRAND / "brand.json").read_bytes()
    files[ROOT / "mobile/android/app/src/main/res/values/brand_strings.xml"] = android_strings(brand).encode("utf-8")
    files[ROOT / "mobile/assets/brand/logos.json"] = logos_json
    files[ROOT / "admin/src/brand/logos.json"] = logos_json
    for logo in sorted((BRAND / "logos").iterdir()):
        files[ROOT / "mobile/assets/brand" / logo.name] = logo.read_bytes()
        files[ROOT / "admin/public/brand" / logo.name] = logo.read_bytes()
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    stale = [p for p, data in targets().items() if not p.exists() or p.read_bytes() != data]
    if a.check:
        for p in stale:
            print("out of date:", p.relative_to(ROOT))
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(targets()[p])
        print("wrote", p.relative_to(ROOT))
    print(f"{len(stale)} file(s) written" if stale else "everything up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
